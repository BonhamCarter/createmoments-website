const state = {
  lang: localStorage.getItem('createmoments-language') || ((navigator.language || '').toLowerCase().startsWith('de') ? 'de' : 'en')
};

function setLanguage(lang, persist = true) {
  state.lang = translations[lang] ? lang : 'en';
  document.documentElement.lang = state.lang;
  if (persist) {
    localStorage.setItem('createmoments-language', state.lang);
  }

  document.querySelectorAll('[data-i18n]').forEach((element) => {
    const key = element.dataset.i18n;
    element.innerHTML = translations[state.lang][key] || '';
  });

  document.querySelectorAll('[data-set-lang]').forEach((button) => {
    button.classList.toggle('is-active', button.dataset.setLang === state.lang);
    button.setAttribute('aria-pressed', String(button.dataset.setLang === state.lang));
  });
}

function showViewFromHash() {
  const pathView = location.pathname.replace(/\/$/, '').split('/').pop();
  const viewName = ['privacy', 'imprint'].includes(pathView)
    ? pathView
    : (location.hash || '#home').replace('#', '') || 'home';
  const nextView = document.querySelector(`[data-view="${viewName}"]`) ? viewName : 'home';

  document.querySelectorAll('[data-view]').forEach((view) => {
    view.classList.toggle('is-active', view.dataset.view === nextView);
  });

  if (nextView !== 'home') {
    document.querySelector(`[data-view="${nextView}"]`).focus({ preventScroll: true });
    window.scrollTo({ top: 0, behavior: 'smooth' });
  }
}

document.querySelectorAll('[data-set-lang]').forEach((button) => {
  button.addEventListener('click', () => setLanguage(button.dataset.setLang));
});

window.addEventListener('hashchange', showViewFromHash);

setLanguage(state.lang, false);
showViewFromHash();
